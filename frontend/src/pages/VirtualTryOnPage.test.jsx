import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { MemoryRouter } from 'react-router-dom';
import VirtualTryOnPage from './VirtualTryOnPage';
import { api } from '../lib/api';
jest.mock('../lib/api', () => ({ api: { get: jest.fn(), post: jest.fn() }, apiError: () => 'Error', formatIDR: value => `Rp ${value}`, imageSrc: value => value }));
const mockRefreshCartCount = jest.fn();
jest.mock('../contexts/AuthContext', () => ({ useAuth: () => ({ user: { user_id: 'customer' }, refreshCartCount: mockRefreshCartCount }) }));
jest.mock('../components/VirtualTryOn', () => ({ TryOnStudio: ({ name, stageOverlay, stageFooter }) => <section data-testid="studio"><input aria-label="Camera state" defaultValue="camera-running" /><p>{name}</p>{stageOverlay}{stageFooter}</section> }));
jest.mock('sonner', () => ({ toast: { success: jest.fn() } }));
let host, root;
const products = ['A', 'B'].map((name, i) => ({ id: name, name: `Frame ${name}`, price: 1000 + i, main_image: '/frame.png', sku: name, variants: [{ id: `variant-${name}`, stock: 5, reserved: 0, sku: name, price_override: 2000 + i }], try_on_assets: [{ id: `asset-${name}`, asset_type: 'image' }] }));
beforeEach(() => { jest.useFakeTimers(); jest.clearAllMocks(); api.get.mockResolvedValue({ data: { products, next_offset: null } }); api.post.mockResolvedValue({ data: {} }); host = document.createElement('div'); document.body.appendChild(host); root = createRoot(host); });
afterEach(async () => { if (root) await act(async () => root.unmount()); host.remove(); jest.useRealTimers(); delete window.matchMedia; });
test('hiding details and changing frames preserve the camera and selected cart variant', async () => {
  await act(async () => root.render(<MemoryRouter><VirtualTryOnPage /></MemoryRouter>));
  await act(async () => jest.advanceTimersByTime(250));
  const studio = host.querySelector('[data-testid="studio"]'); studio.querySelector('input').value = 'active-stream-1';
  const details = host.querySelector('#vto-product-details');
  const hide = host.querySelector('[aria-label="Sembunyikan detail produk"]');
  const show = host.querySelector('[aria-label="Tampilkan detail produk"]');
  expect(details.hidden).toBe(false);
  await act(async () => hide.click());
  expect(details.hidden).toBe(true);
  expect(show.hidden).toBe(false);
  expect(document.activeElement).toBe(show);
  const second = [...host.querySelectorAll('aside button')].find(b => b.textContent.includes('Frame B'));
  await act(async () => second.click());
  expect(host.querySelector('[data-testid="studio"]')).toBe(studio);
  expect(studio.querySelector('input').value).toBe('active-stream-1');
  expect(studio.textContent).toContain('Rp 2001');
  expect(details.hidden).toBe(true);
  await act(async () => show.click());
  expect(details.hidden).toBe(false);
  expect(show.hidden).toBe(true);
  expect(document.activeElement).toBe(hide);
  await act(async () => [...studio.querySelectorAll('button')].find(b => b.textContent === 'Beli').click());
  expect(api.post).toHaveBeenCalledWith('/cart', { product_id: 'B', variant_id: 'variant-B', quantity: 1 });
  expect(mockRefreshCartCount).toHaveBeenCalledTimes(1);
});

test('mobile fullscreen is released on desktop resize and when leaving the page', async () => {
  let change;
  const viewport = { matches: true, addEventListener: jest.fn((_event, callback) => { change = callback; }), removeEventListener: jest.fn() };
  window.matchMedia = jest.fn(() => viewport);
  await act(async () => root.render(<MemoryRouter><VirtualTryOnPage /></MemoryRouter>));
  expect(document.documentElement.classList.contains('vto-mobile-active')).toBe(true);
  viewport.matches = false; await act(async () => change());
  expect(document.documentElement.classList.contains('vto-mobile-active')).toBe(false);
  viewport.matches = true; await act(async () => change());
  await act(async () => root.unmount()); root = null;
  expect(document.documentElement.classList.contains('vto-mobile-active')).toBe(false);
  expect(viewport.removeEventListener).toHaveBeenCalledWith('change', change);
});
